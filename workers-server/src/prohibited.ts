function foldKana(c: string): string {
  const x = c.charCodeAt(0);
  if ((x >= 0x3041 && x <= 0x3096) || x === 0x309d || x === 0x309e) return String.fromCharCode(x + 0x60);
  return c;
}
/** 규칙 용어 정규화 — 소문자 + 히라가나 접기 (한글 자모는 그대로). */
