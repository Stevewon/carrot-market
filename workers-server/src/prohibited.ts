interface Norm {
  /** 원문 (NFC) */
  src: string;
  /** 정규화된 압축 문자열 */
  s: string;
  /** s[i] 가 대응하는 src 구간 [start, end) */
  start: number[];
  end: number[];
}

function normalize(raw: string, leet: boolean): Norm {
  const src = (raw || '').normalize('NFC');
  const chars: string[] = [];
  const st: number[] = [];
  const en: number[] = [];
  let i = 0;
  for (const ch of src) {
    const len = ch.length;
    let out = '';
    if (isSyllable(ch) || isCompatJamo(ch)) {
      out = ch;
    } else {
      let n = ch.normalize('NFKC').toLowerCase();
      if (leet) n = n.replace(/[0134578@$!|]/g, (m) => LEET[m] ?? m);
      for (const c of n) {
        if ((c >= 'a' && c <= 'z') || (c >= '0' && c <= '9') || isSyllable(c) || isCompatJamo(c)) out += c;
        else if (isJaChar(c)) out += foldKana(c);
        else if ((c.charCodeAt(0) === 0x3099 || c.charCodeAt(0) === 0x309a) && chars.length && !out) {
          // 반각 탁점·반탁점 (ｼｬﾌﾞ → ブ) — 앞 글자와 합성
          const k = chars.length - 1;
          chars[k] = foldKana((chars[k] + c).normalize('NFC'));
          en[k] = i + len;
        }
      }
    }
    for (const c of out) {
      chars.push(c);
      st.push(i);
      en.push(i + len);
    }
    i += len;
  }

  // 분해 자모 재조합: 초성 + 중성 (+ 종성) → 음절. 단독 모음은 제거 ("대ㅡ마").
  const oc: string[] = [];
  const os: number[] = [];
  const oe: number[] = [];
  for (let k = 0; k < chars.length; k++) {
    const c = chars[k];
    const li = CHO.indexOf(c);
    if (li >= 0 && k + 1 < chars.length && isVowel(chars[k + 1])) {
      const vi = chars[k + 1].charCodeAt(0) - 0x314f;
      let ti = 0;
      let last = k + 1;
      if (k + 2 < chars.length) {
        const t = JONG.indexOf(chars[k + 2]);
        if (t > 0 && !(k + 3 < chars.length && isVowel(chars[k + 3]))) {
          ti = t;
          last = k + 2;
        }
      }
      oc.push(String.fromCharCode(0xac00 + (li * 21 + vi) * 28 + ti));
      os.push(st[k]);
      oe.push(en[last]);
      k = last;
      continue;
    }
    if (isVowel(c)) continue;
    oc.push(c);
    os.push(st[k]);
    oe.push(en[k]);
  }
  return { src, s: oc.join(''), start: os, end: oe };
}

function latinTokens(raw: string, leet: boolean): Set<string> {
  let s = (raw || '').normalize('NFKC').toLowerCase();
  if (leet) s = s.replace(/[0134578@$!|]/g, (m) => LEET[m] ?? m);
  return new Set(s.split(/[^a-z0-9]+/).filter(Boolean));
}

function indexesOf(hay: string, needle: string): number[] {
  const out: number[] = [];
  if (!needle) return out;
  let p = hay.indexOf(needle);
  while (p >= 0) {
    out.push(p);
    p = hay.indexOf(needle, p + 1);
  }
  return out;
}

